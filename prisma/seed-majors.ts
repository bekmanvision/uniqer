async function main() {
  console.log('Updating majors for all Kazakh universities...\n')

  for (const [slug, majors] of Object.entries(universityMajors)) {
    const uni = await prisma.university.findFirst({ where: { slug } })
    if (!uni) {
      console.log(`[SKIP] University with slug "${slug}" not found`)
      continue
    }

    await prisma.university.update({
      where: { id: uni.id },
      data: { majors },
    })

    console.log(`[OK] ${uni.name}: ${majors.length} majors`)
  }

  console.log('\nDone!')
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
